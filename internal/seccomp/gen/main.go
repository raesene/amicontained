// Command gen generates the per-architecture syscall tables used by the
// seccomp prober from the SYS_* constants in golang.org/x/sys/unix.
//
// It is invoked via go:generate from internal/seccomp; run
// `go generate ./internal/seccomp` after bumping golang.org/x/sys.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	arch := flag.String("arch", "", "GOARCH to generate the table for")
	out := flag.String("o", "", "output file")
	flag.Parse()
	if *arch == "" || *out == "" {
		log.Fatal("usage: gen -arch <goarch> -o <file>")
	}

	dir, err := exec.Command("go", "list", "-f", "{{.Dir}}", "golang.org/x/sys/unix").Output()
	if err != nil {
		log.Fatalf("locating golang.org/x/sys/unix: %v", err)
	}
	src := filepath.Join(strings.TrimSpace(string(dir)), "zsysnum_linux_"+*arch+".go")

	f, err := parser.ParseFile(token.NewFileSet(), src, nil, 0)
	if err != nil {
		log.Fatalf("parsing %s: %v", src, err)
	}

	type entry struct {
		nr   int
		name string
	}
	var entries []entry
	seen := map[int]bool{}
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		for _, spec := range gd.Specs {
			vs := spec.(*ast.ValueSpec)
			for i, ident := range vs.Names {
				if !strings.HasPrefix(ident.Name, "SYS_") || i >= len(vs.Values) {
					continue
				}
				lit, ok := vs.Values[i].(*ast.BasicLit)
				if !ok || lit.Kind != token.INT {
					continue
				}
				nr, err := strconv.Atoi(lit.Value)
				if err != nil {
					log.Fatalf("%s: %v", ident.Name, err)
				}
				// Keep the first name if x/sys ever aliases a number.
				if seen[nr] {
					continue
				}
				seen[nr] = true
				entries = append(entries, entry{nr, strings.ToLower(strings.TrimPrefix(ident.Name, "SYS_"))})
			}
		}
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].nr < entries[j].nr })

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gen/main.go from golang.org/x/sys/unix; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "//go:build linux && %s\n\npackage seccomp\n\n", *arch)
	fmt.Fprintf(&buf, "var syscallTable = []syscallEntry{\n")
	for _, e := range entries {
		fmt.Fprintf(&buf, "\t{%d, %q},\n", e.nr, e.name)
	}
	fmt.Fprintf(&buf, "}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("formatting output: %v", err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
